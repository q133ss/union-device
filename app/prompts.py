"""Промпты для генерации карточки товара.

Промпт решает две задачи одновременно:
* получить готовый к публикации текст, а не «эссе о приборе»;
* не дать модели придумать характеристики — ей прямо запрещено использовать
  что-либо, кроме блока «ДАННЫЕ ТОВАРА», и предписано писать «данных нет».

Схема ответа описана в ``RESPONSE_SCHEMA`` и дублируется в системном промпте:
модель видит и правила, и точный формат JSON.
"""

from __future__ import annotations

import json
from typing import Sequence

from app.models import ProductInput
from app.validation import Gap

MAX_TITLE_LENGTH = 70
DESCRIPTION_MIN = 800
DESCRIPTION_MAX = 1200
QUERIES_MIN = 3
QUERIES_MAX = 5
COMMERCIAL_MIN = 300
COMMERCIAL_MAX = 600

RESPONSE_SCHEMA: dict[str, str] = {
    "seo_title": f"string, до {MAX_TITLE_LENGTH} символов, одна строка",
    "seo_description": f"string, от {DESCRIPTION_MIN} до {DESCRIPTION_MAX} символов",
    "specs": "array of {name: string, value: string}",
    "search_queries": f"array of string, от {QUERIES_MIN} до {QUERIES_MAX} запросов",
    "commercial_block": f"string, от {COMMERCIAL_MIN} до {COMMERCIAL_MAX} символов",
    "data_gaps": "array of string",
    "warnings": "array of string",
}

SYSTEM_PROMPT = f"""Ты — контент-редактор B2B-интернет-магазина контрольно-измерительных \
приборов (КИП). Ты готовишь карточки товаров для инженера-снабженца, метролога и \
специалиста по автоматизации: люди читают их, чтобы понять, подходит ли прибор под \
задачу, и уже потом идут в отдел продаж.

ГЛАВНОЕ ПРАВИЛО
В карточке не должно быть ни одного факта, которого нет в блоке «ДАННЫЕ ТОВАРА».
Данные — единственный источник истины. Твои знания о приборах, брендах и отраслях \
использовать для фактов нельзя.

ЗАПРЕЩЕНО
1. Добавлять характеристики, цифры, единицы измерения, диапазоны, материалы, \
степени защиты, сертификаты, поверку, гарантию, страну происхождения, аналоги и \
совместимость — если их нет в данных.
2. Округлять, пересчитывать единицы, «уточнять» значения по смыслу. Числа и \
маркировки переноси дословно, как во входных данных.
3. Придумывать цены, наличие, сроки поставки, скидки и условия.
4. Писать оценочные штампы: «лучший», «№1», «самый надёжный», «не имеет аналогов».
5. Копировать входное описание дословно — его нужно переписать своими словами, \
сохранив все факты.

ЕСЛИ ДАННЫХ НЕТ
Отсутствующую характеристику пиши как «данных нет» и обязательно перечисляй её в \
data_gaps. Если характеристика не нужна для этой карточки — просто не упоминай её, \
но в data_gaps она всё равно попадает. Пустое место лучше выдумки: одна \
недостоверная цифра делает карточку браком.

ЧТО НУЖНО СДЕЛАТЬ
1. seo_title — заголовок для выдачи и title страницы, до {MAX_TITLE_LENGTH} символов.
   Формула: тип прибора + бренд + модель + 1 ключевая характеристика или назначение.
   Без точки в конце, без кавычек-ёлочек, без «купить» в начале.
2. seo_description — связный текст {DESCRIPTION_MIN}–{DESCRIPTION_MAX} символов, \
3–5 абзацев, без списков, без цен. Абзацы: (1) что это за прибор и для чего он; \
(2) ключевые технические характеристики из данных; (3) какие задачи и в каких \
отраслях решает, кому подходит; (4) на что обратить внимание при выборе — только \
на основе имеющихся характеристик. Ключевые слова (тип прибора, модель, назначение) \
используй естественно, 1–2 раза прямо называй модель.
3. specs — 6–12 самых важных характеристик. name — как во входных данных, value — \
дословно из данных. Характеристики без значения не включай.
4. search_queries — {QUERIES_MIN}–{QUERIES_MAX} поисковых запросов, как их реально \
вводит покупатель: 2–6 слов, без кавычек, без названий конкурентов. Смешай \
транзакционные («купить …»), сравнительные («… характеристики») и прикладные \
(«… для …»).
5. commercial_block — {COMMERCIAL_MIN}–{COMMERCIAL_MAX} символов для менеджера: \
кому подходит прибор (2–3 сегмента клиентов), какие задачи закрывает, что уточнить \
у клиента перед подбором. Без цен и обещаний сроков.
6. data_gaps — короткий список отсутствующих характеристик (по-русски, без \
пояснений).
7. warnings — что контент-менеджеру стоит проверить или уточнить у поставщика.

ФОРМАТ ОТВЕТА
Верни ТОЛЬКО валидный JSON-объект без markdown-разметки, комментариев и текста до \
или после него. Схема:
{json.dumps(RESPONSE_SCHEMA, ensure_ascii=False, indent=2)}

Пиши по-русски, деловым языком без воды и канцелярита."""


def build_user_prompt(product: ProductInput, gaps: Sequence[Gap]) -> str:
    """Собирает пользовательское сообщение: данные прибора + список пропусков."""
    payload = {
        "name": product.name,
        "manufacturer": product.manufacturer,
        "category": product.category,
        "specs": product.specs,
        "description": product.description,
    }
    data_json = json.dumps(payload, ensure_ascii=False, indent=2)

    if gaps:
        gap_lines = "\n".join(f"- {gap.label} — {gap.hint}" for gap in gaps)
        gaps_block = (
            "ЧЕГО НЕТ ВО ВХОДНЫХ ДАННЫХ (по чек-листу карточки КИП).\n"
            "Если это важно для описания — пиши «данных нет» и включай пункт в data_gaps. "
            "Не додумывай значения:\n"
            f"{gap_lines}"
        )
    else:
        gaps_block = (
            "ЧЕГО НЕТ ВО ВХОДНЫХ ДАННЫХ: чек-лист пройден полностью. "
            "Всё равно не добавляй ничего сверх блока «ДАННЫЕ ТОВАРА»."
        )

    return (
        "ДАННЫЕ ТОВАРА (единственный источник фактов):\n"
        f"{data_json}\n\n"
        f"{gaps_block}\n\n"
        "Собери карточку товара по правилам системного сообщения. "
        "Ответ — только JSON-объект по схеме."
    )


def build_repair_prompt(
    product: ProductInput,
    draft: dict,
    violations: Sequence[str],
) -> str:
    """Промпт для исправления карточки после проверки на выдуманные данные."""
    payload = {
        "name": product.name,
        "manufacturer": product.manufacturer,
        "category": product.category,
        "specs": product.specs,
        "description": product.description,
    }
    problems = "\n".join(f"- {item}" for item in violations)
    return (
        "Твоя карточка не прошла проверку на достоверность.\n\n"
        "ДАННЫЕ ТОВАРА (единственный источник фактов):\n"
        f"{json.dumps(payload, ensure_ascii=False, indent=2)}\n\n"
        "ЧЕРНОВИК КАРТОЧКИ:\n"
        f"{json.dumps(draft, ensure_ascii=False, indent=2)}\n\n"
        "НАЙДЕННЫЕ НАРУШЕНИЯ:\n"
        f"{problems}\n\n"
        "Исправь только эти нарушения: убери или замени на «данных нет» всё, чего нет "
        "в данных товара, и не добавляй новых фактов. Сохрани структуру и объёмы "
        f"(заголовок до {MAX_TITLE_LENGTH}, описание {DESCRIPTION_MIN}–{DESCRIPTION_MAX} "
        f"символов, {QUERIES_MIN}–{QUERIES_MAX} запросов).\n"
        "Верни только исправленный JSON-объект по той же схеме."
    )
